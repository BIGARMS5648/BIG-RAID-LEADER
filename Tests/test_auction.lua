T.test("14. 낙찰 취소 + 15. 환불 처리", function()
    local BRL = setup()
    local a = runAuction(link(16, "환불"), { { "대원6", "1200" } })
    M.Advance(31)
    local aw = BRL.Auctions:ConfirmAward(a.id)
    local tr = trade("대원6", 1200 * G)
    BRL.Payments:AllocateAuction(tr.id, aw.id, 1200 * G)
    T.no(BRL.Auctions:CancelAward(aw.id, ""), "사유 필수")
    T.ok(BRL.Auctions:CancelAward(aw.id, "아이템 오류"))
    local st = BRL.Payments:AwardStatus(aw)
    T.eq(st.status, "refund_due")
    T.eq(st.refundDue, 1200 * G)
    local sum = BRL.Ledger:Summary(aw.sessionId)
    T.eq(sum.totalAwarded, 0, "취소된 낙찰 제외")
    T.eq(sum.collected, 0, "분배 대상 수금에서 제외")
    T.eq(sum.refundDue, 1200 * G)
    local rt = trade("대원6", 0, 1200 * G)
    T.ok(BRL.Payments:AllocateRefund(rt.id, aw.id, 1200 * G))
    st = BRL.Payments:AwardStatus(aw)
    T.eq(st.status, "refunded")
    sum = BRL.Ledger:Summary(aw.sessionId)
    T.eq(sum.balance, 0, "환불 후 잔액 0")
    -- 재경매 가능
    T.ok(BRL.Auctions:Relist(a.id))
end)

T.test("즉시 낙찰가 / 막판 연장 / 아이템 전달 자동 감지", function()
    local BRL = setup()
    BRL.acct.auction.antiSnipeSeconds = 10
    local auc = runAuction(link(17, "즉낙"), {}, { buyout = 1000 * G })
    M.Advance(25)
    BRL.Bids:Place(auc.id, "대원2", 200 * G, "manual")
    T.ok(BRL.Auctions:Remaining(auc) >= 9.9, "막판 입찰 연장")
    BRL.Bids:Place(auc.id, "대원3", 1000 * G, "manual")
    T.eq(auc.status, "ended", "즉시 낙찰가 도달 시 종료")
    local aw = BRL.Auctions:ConfirmAward(auc.id)
    T.eq(aw.winnerKey, "대원3-아즈샤라")
    local tr = trade("대원3", 1000 * G, 0, { { name = "즉낙", link = link(17, "즉낙"), count = 1 } })
    T.ok(aw.delivered, "아이템 전달 감지")
    T.eq(aw.deliveredTradeId, tr.id)
    -- 자동 제안만 하고 확정하지 않음
    T.eq(BRL.Payments:AwardStatus(aw).collected, 0, "자동 확정 안 함")
    T.ok(tr.suggestion and tr.suggestion.allocations[1].exact, "정확히 일치 제안")
end)

