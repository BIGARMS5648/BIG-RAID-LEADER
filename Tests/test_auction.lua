-- 23.2 골드 경매 테스트 (+ 14. 경매와 실제 거래 연결)
local M = MOCK
local G = 10000

local function setup()
    local BRL = T.fresh({ group = T.raid(10) })
    BRL.acct.auction.startPrice = 100 * G
    BRL.acct.auction.minIncrement = 50 * G
    BRL.acct.auction.defaultDuration = 30
    local s = BRL.Session:Create({ name = "경매 테스트", raidKey = "BARROW_DEEPS" })
    return BRL, s
end

local function link(id, name) return M.ItemLink(id, name) end

-- 완료된 거래 생성 (자동 기록 경로 사용)
local function trade(partner, received, given, items)
    M.trade = { partner = partner, playerMoney = given or 0, targetMoney = received or 0, playerItems = items or {}, targetItems = {} }
    M.Fire("TRADE_SHOW")
    M.Fire("TRADE_ACCEPT_UPDATE", 1, 0)
    M.money = M.money + (received or 0) - (given or 0)
    M.Fire("UI_INFO_MESSAGE", 0, ERR_TRADE_COMPLETE)
    M.Fire("TRADE_CLOSED")
    M.Fire("PLAYER_MONEY")
    M.Advance(4)
    return BRL.TradeJournal:Query({})[1]
end

local function runAuction(itemLink, bids, opts)
    local auc = assert(BRL.Auctions:Add(itemLink, opts))
    assert(BRL.Auctions:Start(auc.id))
    for _, b in ipairs(bids or {}) do
        M.Fire("CHAT_MSG_RAID", b[2], b[1] .. "-아즈샤라")
    end
    return auc
end

T.test("1. 정상 입찰 + 채팅 입찰 인식 + 낙찰 확정", function()
    local BRL = setup()
    local auc = runAuction(link(1, "검"), { { "대원2", "100" }, { "대원3", "150골드" }, { "대원4", "2.5k" } })
    T.eq(auc.highAmount, 2500 * G, "최고가")
    T.eq(auc.highBidder, "대원4-아즈샤라")
    M.Advance(31)
    T.eq(auc.status, "ended", "타이머 종료")
    local aw = BRL.Auctions:ConfirmAward(auc.id)
    T.ok(aw, "낙찰")
    T.eq(aw.amount, 2500 * G)
    T.eq(auc.status, "awarded")
    local st = BRL.Payments:AwardStatus(aw)
    T.eq(st.collected, 0, "낙찰액을 실제 수령으로 합산하지 않음")
    T.eq(st.outstanding, 2500 * G, "미수금")
end)

