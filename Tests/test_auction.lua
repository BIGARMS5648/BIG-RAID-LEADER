T.test("8. 동일 플레이어 여러 아이템 낙찰 + 9. 부분 입금 + 10. 합산 입금", function()
    local BRL = setup()
    local a1 = runAuction(link(8, "A"), { { "대원2", "1000" } })
    M.Advance(31)
    local aw1 = BRL.Auctions:ConfirmAward(a1.id)
    local a2 = runAuction(link(9, "B"), { { "대원2", "2000" } })
    M.Advance(31)
    local aw2 = BRL.Auctions:ConfirmAward(a2.id)
    T.eq(#BRL.Auctions:AwardsForPlayer("대원2-아즈샤라"), 2)
    -- 부분 입금 (14장 예시)
    local tr1 = trade("대원2", 500 * G)
    local sug = BRL.Payments:SuggestAuctionAllocations(tr1)
    T.eq(#sug, 1)
    T.eq(sug[1].awardId, aw1.id, "오래된 낙찰부터 제안")
    T.ok(BRL.Payments:AllocateAuction(tr1.id, aw1.id, 500 * G))
    local st1 = BRL.Payments:AwardStatus(aw1)
    T.eq(st1.status, "partial")
    T.eq(st1.outstanding, 500 * G)
    -- 합산 입금: 한 거래로 나머지 500 + 2000
    local tr2 = trade("대원2", 2500 * G)
    sug = BRL.Payments:SuggestAuctionAllocations(tr2)
    T.eq(#sug, 2, "두 낙찰에 배분 제안")
    T.ok(tr2.suggestion, "거래 기록 시 자동 제안 생성(확정 아님)")
    T.eq(BRL.Payments:AwardStatus(aw2).collected, 0, "제안만으로는 수금 반영 안 됨")
    T.eq(BRL.Payments:ApplySuggestion(tr2.id), 2, "공대장 승인 시 반영")
    T.eq(BRL.Payments:AwardStatus(aw1).status, "paid")
    T.eq(BRL.Payments:AwardStatus(aw2).status, "paid")
    local sum = BRL.Ledger:Summary(aw1.sessionId)
    T.eq(sum.totalAwarded, 3000 * G)
    T.eq(sum.collected, 3000 * G)
    T.eq(sum.outstanding, 0)
end)

T.test("14장 예시: 3000 낙찰 → 2000 입금 → 1000 입금 → 완납", function()
    local BRL = setup()
    local a = runAuction(link(10, "예시"), { { "대원5", "3000" } })
    M.Advance(31)
    local aw = BRL.Auctions:ConfirmAward(a.id)
    local st = BRL.Payments:AwardStatus(aw)
    T.eq(st.collected, 0) T.eq(st.outstanding, 3000 * G)
    local t1 = trade("대원5", 2000 * G)
    BRL.Payments:AllocateAuction(t1.id, aw.id, 2000 * G)
    st = BRL.Payments:AwardStatus(aw)
    T.eq(st.collected, 2000 * G) T.eq(st.outstanding, 1000 * G)
    local t2 = trade("대원5", 1000 * G)
    BRL.Payments:AllocateAuction(t2.id, aw.id, 1000 * G)
    st = BRL.Payments:AwardStatus(aw)
    T.eq(st.collected, 3000 * G) T.eq(st.outstanding, 0) T.eq(st.status, "paid", "완납")
end)

